  maybeOpenShift: (name)   => ipcRenderer.invoke('maybe-open-shift', name),
  getSettings:   ()        => ipcRenderer.invoke('get-settings'),
  updateSetting: (data)    => ipcRenderer.invoke('update-setting', data),
  checkBaseLoaded: ()      => ipcRenderer.invoke('check-base-loaded'),
  loadInitialBase: (type)  => ipcRenderer.invoke('load-initial-base', type),
  getCashiers:   ()        => ipcRenderer.invoke('get-cashiers'),
  addCashier:    (data)    => ipcRenderer.invoke('add-cashier', data),
  deleteCashier: (id)      => ipcRenderer.invoke('delete-cashier', id),
  updateCashierPin: (data) => ipcRenderer.invoke('update-cashier-pin', data),
  exportDB:      (name)    => ipcRenderer.invoke('export-db', name),
  importDB:      ()        => ipcRenderer.invoke('import-db'),
  optimizeDatabase: ()     => ipcRenderer.invoke('optimize-database'),
  autoBackupDB:  ()        => ipcRenderer.invoke('auto-backup-db'),
  writeOffProduct: (data)  => ipcRenderer.invoke('write-off-product', data),
  getWriteOffs:  ()        => ipcRenderer.invoke('get-write-offs'),
  getInventoryLogs: (opts) => ipcRenderer.invoke('get-inventory-logs', opts),
  addExpense:    (data)    => ipcRenderer.invoke('add-expense', data),
  deleteExpense: (id)      => ipcRenderer.invoke('delete-expense', id),
  deleteCustomer: (data)   => ipcRenderer.invoke('delete-customer', data),
  getMachineId:  ()        => ipcRenderer.invoke('get-machine-id'),
  getActivation: ()        => ipcRenderer.invoke('get-activation'),
  saveActivation:(fingerprint) => ipcRenderer.invoke('save-activation', fingerprint),
  clearActivation:()       => ipcRenderer.invoke('clear-activation')
